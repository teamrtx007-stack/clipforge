-- ClipForge's tables for PostgreSQL (Supabase), the same as the SQLite schema in app/db.py.
-- Kept in step with supabase/migrations/*_clipforge_schema.sql (a test checks they match).
-- Types follow SQLite's: times are seconds since 1970 (double precision), JSON documents are text,
-- on/off flags are integers. Ids are never reused: files and queued jobs refer to them.
CREATE SCHEMA IF NOT EXISTS clipforge;

CREATE TABLE IF NOT EXISTS clipforge.projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  settings TEXT NOT NULL DEFAULT '{}',
  created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS clipforge.channels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES clipforge.projects(id) ON DELETE CASCADE,
  platform TEXT NOT NULL,
  url TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  auto_record INTEGER NOT NULL DEFAULT 1,
  auto_render INTEGER NOT NULL DEFAULT 1,
  chat INTEGER NOT NULL DEFAULT 1,
  speech INTEGER NOT NULL DEFAULT 1,
  sensitivity TEXT NOT NULL DEFAULT 'medium',
  template TEXT NOT NULL,
  buffer_minutes INTEGER NOT NULL DEFAULT 5,
  created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS clipforge.sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES clipforge.projects(id) ON DELETE CASCADE,
  channel_id BIGINT REFERENCES clipforge.channels(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('upload', 'live')),
  name TEXT NOT NULL,
  ext TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('uploading', 'queued', 'processing', 'ready', 'failed')),
  stage TEXT NOT NULL DEFAULT '',
  progress DOUBLE PRECISION NOT NULL DEFAULT 0,
  duration DOUBLE PRECISION,
  width INTEGER,
  height INTEGER,
  fps DOUBLE PRECISION,
  meta TEXT NOT NULL DEFAULT '{}',
  error TEXT,
  created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS clipforge.clips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id BIGINT NOT NULL REFERENCES clipforge.sources(id) ON DELETE CASCADE,
  start DOUBLE PRECISION NOT NULL,
  "end" DOUBLE PRECISION NOT NULL CHECK ("end" > start),
  peak DOUBLE PRECISION,
  score DOUBLE PRECISION NOT NULL DEFAULT 0,
  title TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  hashtags TEXT NOT NULL DEFAULT '[]',
  reasons TEXT NOT NULL DEFAULT '[]',
  template TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('draft', 'queued', 'rendering', 'ready', 'failed')),
  progress DOUBLE PRECISION NOT NULL DEFAULT 0,
  error TEXT,
  created_at DOUBLE PRECISION NOT NULL,
  rendered_at DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS clipforge.jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  target_id BIGINT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('queued', 'running', 'done', 'failed')),
  priority INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  error TEXT,
  created_at DOUBLE PRECISION NOT NULL,
  updated_at DOUBLE PRECISION NOT NULL
);
-- One row per finished piece of work, for the dashboard chart. It outlives the videos and clips it counts.
CREATE TABLE IF NOT EXISTS clipforge.activity (
  kind TEXT NOT NULL CHECK (kind IN ('video', 'clip', 'moment')),
  at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS activity_at ON clipforge.activity (at);
-- Every stored copy of a file in object storage (R2 primary, B2 backup), one row per copy.
CREATE TABLE IF NOT EXISTS clipforge.files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL DEFAULT 'local',
  owner_kind TEXT NOT NULL CHECK (owner_kind IN ('source', 'clip')),
  owner_id BIGINT NOT NULL,
  file_type TEXT NOT NULL,
  storage_provider TEXT NOT NULL,
  object_key TEXT NOT NULL,
  file_size BIGINT NOT NULL DEFAULT 0,
  md5 TEXT,
  upload_status TEXT NOT NULL CHECK (upload_status IN ('pending', 'uploaded', 'failed', 'deleting')),
  backup_status TEXT NOT NULL DEFAULT 'none' CHECK (backup_status IN ('none', 'pending', 'verified', 'failed', 'skipped')),
  error TEXT,
  created_at DOUBLE PRECISION NOT NULL,
  updated_at DOUBLE PRECISION NOT NULL,
  expires_at DOUBLE PRECISION,
  UNIQUE (storage_provider, object_key)
);
CREATE INDEX IF NOT EXISTS files_owner ON clipforge.files (owner_kind, owner_id, file_type);
CREATE INDEX IF NOT EXISTS jobs_claim ON clipforge.jobs (status, priority DESC, id);
-- Several workers may queue the same work at once; only one queued job per target survives.
CREATE UNIQUE INDEX IF NOT EXISTS jobs_one_queued ON clipforge.jobs (kind, target_id) WHERE status = 'queued';
CREATE INDEX IF NOT EXISTS sources_project ON clipforge.sources (project_id);
CREATE INDEX IF NOT EXISTS clips_source ON clipforge.clips (source_id);
